ZERO_FINDINGS_MANDATED_TEXT = "Not found in the sources queried"


def _check_compile_permission(case: Case, user: User):
    """Ensure user is operator or compliance_admin and not the reviewer."""
    if not user.is_active:
        raise HTTPException(status_code=403, detail="Inactive user account.")
    if user.id == case.reviewer_id:
        raise HTTPException(
            status_code=403,
            detail="Bilateral separation violation: Assigned reviewer cannot compile dossier.",
        )
    if user.role not in (UserRole.operator.value, UserRole.compliance_admin.value):
        raise HTTPException(status_code=403, detail="Only an operator or Compliance Administrator can compile dossiers.")


def compile_dossier(
    db: Session,
    case: Case,
    user: User,
    ip: str = "unknown",
) -> Dossier:
    """
    Compile the immutable Dossier for the current version of the case.
    Can be run in BUILD_AND_QA or RELEASE_GATE.
    """
    if case.stage not in (CaseStage.BUILD_AND_QA.value, CaseStage.RELEASE_GATE.value, CaseStage.CLOSED.value):
        raise HTTPException(
            status_code=400,
            detail=f"Cannot compile dossier in stage {case.stage}. Expected BUILD_AND_QA, RELEASE_GATE, or CLOSED.",
        )
    _check_compile_permission(case, user)

    # 1. Fetch case data
    source_runs = (
        db.query(SourceRun)
        .filter(SourceRun.case_id == case.id)
        .order_by(SourceRun.started_at.asc())
        .all()
    )

    claims = (
        db.query(Claim)
        .filter(Claim.case_id == case.id)
        .all()
    )

    accepted_records = (
        db.query(Record)
        .filter(Record.case_id == case.id, Record.triage_status == TriageStatus.ACCEPTED.value)
        .order_by(Record.id.asc())
        .all()
    )

    confirmed_findings = [
        c for c in claims
        if c.review_status == ReviewStatus.APPROVED.value and c.dossier_section == DossierSection.CONFIRMED_FINDING.value
    ]
    unresolved_matches = [
        c for c in claims
        if c.review_status == ReviewStatus.APPROVED.value and c.dossier_section == DossierSection.UNRESOLVED_POSSIBLE_MATCH.value
    ]

    tier1_count = sum(1 for c in claims if c.match_tier == MatchTier.TIER_1.value)
    tier2_count = sum(1 for c in claims if c.match_tier == MatchTier.TIER_2.value)
    tier3_count = sum(1 for c in claims if c.match_tier == MatchTier.TIER_3.value)

    # 2. Build Coverage Manifest Payload
    manifest_items = []
    for sr in source_runs:
        s_code = sr.source.code if sr.source else "UNKNOWN"
        s_name = sr.source.name if sr.source else "Unknown Source"
        s_tier = sr.source.tier if sr.source else "C"
        s_rel = sr.source.default_reliability if sr.source else "C"
        manifest_items.append({
            "source_code": s_code,
            "source_name": s_name,
            "tier": s_tier,
            "reliability": s_rel,
            "query_input": sr.query_input,
            "status": sr.status,
            "started_at": sr.started_at.isoformat() if sr.started_at else None,
            "completed_at": sr.completed_at.isoformat() if sr.completed_at else None,
        })
    manifest_json = json.dumps(manifest_items)

    now_utc = datetime.datetime.now(timezone.utc)
    version = case.dossier_version or 1

    # 3. Build Standalone Modernist HTML Content
    html_content = _render_dossier_html(
        case=case,
        version=version,
        now_utc=now_utc,
        manifest_items=manifest_items,
        confirmed_findings=confirmed_findings,
        unresolved_matches=unresolved_matches,
        accepted_records=accepted_records,
        tier_counts=(tier1_count, tier2_count, tier3_count),
    )

    # 4. Generate Deterministic PDF Bytes
    pdf_bytes = _render_dossier_pdf(
        case=case,
        version=version,
        now_utc=now_utc,
        manifest_items=manifest_items,
        confirmed_findings=confirmed_findings,
        unresolved_matches=unresolved_matches,
        accepted_records=accepted_records,
        tier_counts=(tier1_count, tier2_count, tier3_count),
    )
    pdf_b64 = base64.b64encode(pdf_bytes).decode("ascii")

    # 5. Compute Dossier SHA-256 Hash
    hash_payload = f"{case.case_ref}|v{version}|{now_utc.isoformat()}|{manifest_json}|{len(confirmed_findings)}|{len(unresolved_matches)}"
    dossier_hash = hashlib.sha256(hash_payload.encode("utf-8")).hexdigest()

    # 6. Check if Dossier already exists for this case + version
    existing = (
        db.query(Dossier)
        .filter(Dossier.case_id == case.id, Dossier.version == version)
        .first()
    )
    if existing:
        dossier = existing
        dossier.compiled_by_id = user.id
        dossier.html_content = html_content
        dossier.pdf_bytes_b64 = pdf_b64
        dossier.dossier_hash = dossier_hash
        dossier.coverage_manifest_json = manifest_json
        dossier.confirmed_findings_count = len(confirmed_findings)
        dossier.unresolved_matches_count = len(unresolved_matches)
        dossier.created_at = now_utc
    else:
        dossier = Dossier(
            case_id=case.id,
            version=version,
            compiled_by_id=user.id,
            html_content=html_content,
            pdf_bytes_b64=pdf_b64,
            dossier_hash=dossier_hash,
            coverage_manifest_json=manifest_json,
            confirmed_findings_count=len(confirmed_findings),
            unresolved_matches_count=len(unresolved_matches),
            is_revoked=False,
            created_at=now_utc,
        )
        db.add(dossier)

    db.commit()
    db.refresh(dossier)

    log_action(
        db,
        action="dossier_compiled",
        user_id=user.id,
        case_id=case.id,
        from_stage=case.stage,
        to_stage=case.stage,
        allowed=True,
        detail={
            "dossier_id": dossier.id,
            "version": version,
            "dossier_hash": dossier_hash,
            "confirmed_count": len(confirmed_findings),
            "unresolved_count": len(unresolved_matches),
            "pdf_size_bytes": len(pdf_bytes),
        },
        ip=ip,
        commit=True,
    )

    return dossier


def release_dossier(
    db: Session,
    case: Case,
    user: User,
    ip: str = "unknown",
) -> Dossier:
    """
    Compliance Admin release gate action.
    Generates secure delivery token, expires in 7 days, closes the case.
    """
    if user.role != UserRole.compliance_admin.value:
        raise HTTPException(
            status_code=403,
            detail="Only a Compliance Administrator can release dossiers and close a case.",
        )

    version = case.dossier_version or 1
    dossier = (
        db.query(Dossier)
        .filter(Dossier.case_id == case.id, Dossier.version == version)
        .order_by(Dossier.id.desc())
        .first()
    )
    if not dossier:
        dossier = compile_dossier(db, case, user, ip=ip)

    if dossier.is_revoked:
        raise HTTPException(
            status_code=400,
            detail="Cannot release a revoked dossier. Recompile a new version.",
        )

    now_utc = datetime.datetime.now(timezone.utc)
    token = secrets.token_urlsafe(32)
    expires_at = now_utc + datetime.timedelta(days=7)

    dossier.delivery_token = token
    dossier.delivery_expires_at = expires_at
    dossier.released_by_id = user.id
    dossier.released_at = now_utc

    db.commit()
    db.refresh(dossier)

    log_action(
        db,
        action="dossier_released",
        user_id=user.id,
        case_id=case.id,
        from_stage=case.stage,
        to_stage=CaseStage.CLOSED.value,
        allowed=True,
        detail={
            "dossier_id": dossier.id,
            "version": dossier.version,
            "delivery_token": token,
            "expires_at": expires_at.isoformat(),
        },
        ip=ip,
        commit=True,
    )

    return dossier


def revoke_dossier(
    db: Session,
    case: Case,
    user: User,
    reason: str,
    ip: str = "unknown",
):
    """
    Revoke the active dossier upon case recall.
    """
    if user.role != UserRole.compliance_admin.value:
        raise HTTPException(status_code=403, detail="Only Compliance Administrator can revoke dossiers.")

    active_dossiers = (
        db.query(Dossier)
        .filter(Dossier.case_id == case.id, Dossier.is_revoked == False)
        .all()
    )
    for d in active_dossiers:
        d.is_revoked = True

    db.commit()

    log_action(
        db,
        action="dossier_revoked",
        user_id=user.id,
        case_id=case.id,
        from_stage=case.stage,
        to_stage=CaseStage.RECALLED.value,
        allowed=True,
        detail={"reason": reason, "revoked_count": len(active_dossiers)},
        ip=ip,
        commit=True,
    )


def get_dossier_by_token(db: Session, token: str) -> Optional[Dossier]:
    """Retrieve dossier by secure delivery token for external client verification."""
    return db.query(Dossier).filter(Dossier.delivery_token == token).first()


def get_active_dossier_for_case(db: Session, case_id: int) -> Optional[Dossier]:
    """Retrieve the latest compiled dossier for a case."""
    return (
        db.query(Dossier)
        .filter(Dossier.case_id == case_id)
        .order_by(Dossier.version.desc(), Dossier.id.desc())
        .first()
    )


