def _render_dossier_pdf(
    case: Case,
    version: int,
    now_utc: datetime.datetime,
    manifest_items: List[Dict[str, Any]],
    confirmed_findings: List[Claim],
    unresolved_matches: List[Claim],
    accepted_records: List[Record],
    tier_counts: Tuple[int, int, int],
) -> bytes:
    """Build pure-Python valid %PDF-1.4 binary stream using SimplePDFCanvas."""
    canvas = SimplePDFCanvas(title="CRICE // INTELLIGENCE DOSSIER")

    # Banner
    canvas.add_title_banner(case.case_ref, version)

    # 1. Document Control Block
    canvas.add_section_header("1. Document Control Block")
    canvas.add_kv_row("Case CIN", case.case_ref)
    canvas.add_kv_row("Dossier Version", f"v{version}.0")
    canvas.add_kv_row("Classification", "CONFIDENTIAL // CLIENT-SCOPED")
    canvas.add_kv_row("Issue Timestamp", now_utc.strftime("%Y-%m-%d %H:%M:%S UTC"))
    canvas.add_kv_row("Recall Contact", "compliance@crice.ai")
    canvas.draw_rule()

    # 2. Subject Disambiguation Block
    canvas.add_section_header("2. Subject Disambiguation Profile")
    canvas.add_kv_row("Subject Name", case.subject_name)
    canvas.add_kv_row("Subject Type", case.subject_type.upper())
    canvas.add_kv_row("Primary Identifier", case.subject_identifier or "N/A")
    canvas.add_kv_row("MCA DIN", case.subject_din or "N/A")
    canvas.add_kv_row("PAN / GSTIN", case.subject_pan_or_gstin or "N/A")
    canvas.add_kv_row("DOB / Year", case.subject_dob_or_year or "N/A")
    canvas.add_kv_row("Father / Spouse", case.subject_father_or_spouse or "N/A")
    canvas.add_kv_row("City", case.subject_city or "N/A")
    canvas.add_kv_row("Match Counts", f"Tier 1: {tier_counts[0]} | Tier 2: {tier_counts[1]} | Tier 3: {tier_counts[2]}")
    canvas.draw_rule()

    # 3. Coverage Manifest
    canvas.add_section_header("3. Chartered Coverage Manifest")
    headers = ["Source Code", "Source Name", "Tier", "Rel", "Status"]
    table_rows = []
    for m in manifest_items:
        table_rows.append([
            m["source_code"][:16],
            m["source_name"][:20],
            m["tier"],
            m["reliability"],
            m["status"],
        ])
    canvas.add_table(headers, table_rows, [110, 150, 45, 45, 100])
    canvas.draw_rule()

    # 4. Confirmed Findings
    canvas.add_section_header("4. Confirmed Intelligence Findings")
    if not confirmed_findings:
        canvas.add_callout_box(
            "FINDINGS SUMMARY",
            ZERO_FINDINGS_MANDATED_TEXT + " - All chartered sources returned negative or null matches.",
            border_color=(0, 0.7, 0.9),
            bg_color=(0.95, 0.98, 1.0),
        )
    else:
        for f in confirmed_findings:
            score = f"{f.source_reliability}{f.identity_confidence}"
            canvas.add_finding_card(
                score_badge=score,
                predicate=f.predicate,
                object_value=f.object_value,
                verbatim_quote=f.verbatim_quote,
                primary_record_id=f.primary_record_id,
                snapshot_hash=f.snapshot_hash,
                is_adverse=f.is_adverse,
            )
    canvas.draw_rule()

    # 5. Unresolved Possible Matches
    canvas.add_section_header("5. Unresolved Possible Matches")
    if unresolved_matches:
        canvas.add_callout_box(
            "QUARANTINED MATCHES WARNING",
            UNRESOLVED_WARNING_BANNER,
            border_color=(0.9, 0.6, 0.1),
            bg_color=(1.0, 0.98, 0.92),
        )
        for u in unresolved_matches:
            score = f"{u.source_reliability}{u.identity_confidence}"
            canvas.add_finding_card(
                score_badge=score,
                predicate=f"{u.predicate} (Quarantined)",
                object_value=u.object_value,
                verbatim_quote=u.verbatim_quote,
                primary_record_id=u.primary_record_id,
                snapshot_hash=u.snapshot_hash,
                is_adverse=u.is_adverse,
            )
    else:
        canvas.add_paragraph("No uncorroborated or quarantined candidate matches exist for this subject.")
    canvas.draw_rule()

    # 6. Evidence Appendix
    canvas.add_section_header("6. Evidence Appendix")
    ev_headers = ["Rec ID", "Title", "Source", "Snapshot Hash (snip)"]
    ev_rows = []
    for r in accepted_records:
        s_code = r.source.code if r.source else "UNKNOWN"
        ev_rows.append([
            f"#{r.id}",
            r.title[:24],
            s_code[:14],
            r.snapshot_hash[:18] + "...",
        ])
    canvas.add_table(ev_headers, ev_rows, [50, 160, 110, 180])
    canvas.draw_rule()

    # 7. Methodology, Limitations & Legal Disclaimer
    canvas.add_section_header("7. Methodology & Legal Disclaimer")
    canvas.add_paragraph(LEGAL_DISCLAIMER_TEXT, size=7.5, max_chars=95, color=(0.4, 0.4, 0.4))

    return canvas.build()
